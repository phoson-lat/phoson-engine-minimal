#!/usr/bin/env python3
"""Generate ``docs/cli/reference.md`` from the CLI's own sources of truth.

The command-line options come from ``phoson_cli.__main__._USAGE`` (what
``phoson-cli --help`` prints) and the slash commands from
``phoson_cli.command_catalog.COMMAND_SPECS`` (what ``/help`` lists), so the
reference cannot drift from the code. ``tests/phoson_cli/test_cli_reference.py``
fails when the committed file is stale.

Usage:
    uv run python scripts/gen_cli_reference.py          # rewrite the file
    uv run python scripts/gen_cli_reference.py --check  # exit 1 if stale
"""

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "docs" / "cli" / "reference.md"


def render() -> str:
    sys.path.insert(0, str(ROOT))
    from phoson_cli.__main__ import _USAGE
    from phoson_cli.command_catalog import COMMAND_SPECS

    lines = [
        "# phoson-cli reference",
        "",
        "<!-- Generated by scripts/gen_cli_reference.py — do not edit by hand. -->",
        "",
        "## Command line",
        "",
        "Output of `phoson-cli --help`:",
        "",
        "```text",
        _USAGE.rstrip(),
        "```",
        "",
        "## Slash commands",
        "",
        "Available inside the interactive session (TUI and `--classic`). Plugins",
        "can contribute more; `/help` lists everything active in a session.",
        "",
        "| Command | Aliases | Description |",
        "|---|---|---|",
    ]
    for spec in COMMAND_SPECS:
        aliases = ", ".join(f"`{name}`" for name in spec.names[1:]) or "—"
        description = spec.help.replace("|", "\\|")
        lines.append(f"| `{spec.primary}` | {aliases} | {description} |")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str]) -> int:
    content = render()
    if "--check" in argv:
        current = TARGET.read_text(encoding="utf-8") if TARGET.exists() else ""
        if current != content:
            print(
                f"{TARGET.relative_to(ROOT)} is stale; run "
                "`uv run python scripts/gen_cli_reference.py`"
            )
            return 1
        return 0
    TARGET.write_text(content, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
