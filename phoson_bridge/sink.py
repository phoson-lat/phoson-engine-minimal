"""``GuiSink`` — ``AgentEventSink`` implementation that forwards to the GUI.

One instance per session (one per ``PhosonRepl``/``SessionController``). All
methods are **synchronous** and run on the sidecar loop: nothing is written to
stdout here, it is only enqueued (non-blocking). The server's async writer
drains the queue in order, guaranteeing token/tool ordering.

Equivalent to the CLI's ``ClassicSink``/``FullScreenSink``: a new front-end is
a sink, not a fork.
"""

import dataclasses
from typing import Any
from collections.abc import Callable

from phoson_agent import AgentReasoningEvent

from .protocol import to_jsonable

#: (notification_method, params) -> enqueue, synchronous and non-blocking.
Emit = Callable[[str, dict[str, Any]], None]


def _is_ui_block(block: Any) -> bool:
    """True if *block* is an engine ``UiBlock`` dataclass (not a Rich renderable)."""
    return (
        dataclasses.is_dataclass(block)
        and not isinstance(block, type)
        and type(block).__name__
        in {
            "NoticeBlock",
            "KeyValueBlock",
            "TodoListBlock",
            "ProgressBlock",
        }
    )


class GuiSink:
    """Translate the engine's presentation protocol into JSON notifications."""

    def __init__(self, session_key: str, emit: Emit) -> None:
        self._session_key = session_key
        self._emit = emit
        self._reasoning: list[str] = []
        # Set by `SessionManager` so the `on_session_title` hook can read the
        # title from the tree without coupling the sink to the REPL.
        self.title_provider: Callable[[], str] | None = None
        # Open turns (user or autonomous). The bridge compares it before and
        # after a wake to know whether the turn actually ran.
        self.user_messages = 0

    def _notify(self, method: str, params: dict[str, Any]) -> None:
        self._emit(method, {"sessionId": self._session_key, **params})

    # -- turns ----------------------------------------------------------------
    def on_user_message(self, text: str, message: object) -> None:
        self.user_messages += 1
        self._notify(
            "session.user_message", {"text": text, "message": to_jsonable(message)}
        )

    def on_attachments(self, sources: list[str]) -> None:
        self._notify("attachments.changed", {"sources": list(sources)})

    def on_session_title(self) -> None:
        """The engine updated the session title (heuristic or model-generated).

        Same behavior as the CLI: after the first turn, the title switches from
        the first message to one generated by the model in the background (#55).
        """
        title = ""
        if self.title_provider is not None:
            try:
                title = str(self.title_provider() or "")
            except Exception:  # noqa: BLE001 — never kill the stream over a title
                title = ""
        self._notify("session.title", {"title": title})

    # -- stream ---------------------------------------------------------------
    def on_event(self, event: object) -> None:
        # AgentReasoningEvent/AgentTokenEvent expose `.content` (not `.text`).
        if isinstance(event, AgentReasoningEvent):
            token = getattr(event, "content", None)
            if token:
                self._reasoning.append(token)
        self._notify("agent.event", {"event": to_jsonable(event)})

    def flush_line(self) -> None:
        self._notify("ui.flush", {})

    def capture_partial_reasoning(self) -> None:
        # No-op: reasoning is already accumulated live.
        return None

    def take_reasoning(self) -> str:
        reasoning = "".join(self._reasoning)
        self._reasoning.clear()
        return reasoning

    # -- session / state ------------------------------------------------------
    def set_session(self, session_id: str) -> None:
        self._notify("session.info", {"engineSessionId": session_id})

    def print_history(
        self,
        path: list[object],
        tail: int | None = None,
        timestamps: list | None = None,
        tool_durations: dict[str, int] | None = None,
    ) -> None:
        messages = path if tail is None else path[-tail:]
        stamps = (
            timestamps
            if timestamps is None
            else timestamps[-(tail or len(timestamps)) :]
        )
        self._notify(
            "session.history",
            {
                "messages": [to_jsonable(m) for m in messages],
                "timestamps": to_jsonable(stamps) if stamps is not None else None,
                # `tool_call_id` → ms (engine >= 0.55); the UI does not render it yet.
                "toolDurations": dict(tool_durations or {}),
            },
        )

    def notify(self, kind: str, message: str) -> None:
        self._notify("notify", {"kind": kind, "message": message})

    def on_subagent_progress(self, progress: object | None) -> None:
        self._notify(
            "subagent.progress", {"progress": self._subagent_snapshot(progress)}
        )

    # -- plugin blocks (PluginUiService) --------------------------------------
    #
    # The hooks are named as the engine's `SinkPluginUiService` looks them up via
    # duck-typing. `GuiPluginUiService` calls them with the NEUTRAL block (the
    # dataclass); if a Rich rendering ever arrived (the engine's legacy path), we
    # degrade to text as before instead of breaking.

    def publish_plugin_block(self, block_id: str, block: Any) -> None:
        self._plugin_block(block_id, block, replace=False)

    def replace_plugin_block(self, block_id: str, block: Any) -> None:
        self._plugin_block(block_id, block, replace=True)

    def remove_plugin_block(self, block_id: str) -> None:
        self._notify("plugin.block.remove", {"blockId": block_id})

    def _plugin_block(self, block_id: str, block: Any, *, replace: bool) -> None:
        if not _is_ui_block(block):
            # Legacy path: the engine passed a Rich renderable.
            self.notify("info", str(block))
            return
        self._notify(
            "plugin.block",
            {"blockId": block_id, "block": to_jsonable(block), "replace": replace},
        )

    @staticmethod
    def _subagent_snapshot(progress: object | None) -> Any:
        """Serializable snapshot of the subagent tracker.

        ``SubagentProgressTracker`` is an opaque class (not a dataclass), so
        ``to_jsonable`` would reduce it to a useless ``repr``. We extract its
        ``tasks`` (``SubagentProgress`` is a dataclass) so the UI can render each
        subagent's actual progress.
        """
        if progress is None:
            return None
        tasks = getattr(progress, "tasks", None)
        if tasks is not None:
            return {"tasks": [to_jsonable(t) for t in tasks]}
        return to_jsonable(progress)
